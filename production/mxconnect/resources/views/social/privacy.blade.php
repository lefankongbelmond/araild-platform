    <h1 style="font-size:26px">Politique de confidentialité</h1>
    <p class="mx-small mx-muted">Résumé des règles appliquées par la plateforme. Le texte juridique complet est fourni par l'exploitant du réseau.</p>
    <h2 style="font-size:18px">Données collectées</h2>
    <ul style="padding-left:18px">
      <li>Compte : nom, prénom, téléphone, e-mail facultatif, mot de passe (stocké sous forme chiffrée irréversible).</li>
      <li>Profil facultatif : photo, ville, présentation, centres d'intérêt, visibilité choisie.</li>
      <li>Activité : publications, commentaires, réactions, enregistrements, abonnements, signalements.</li>
      <li>Messages de contact et messages privés : visibles uniquement par vous et la mutuelle concernée.</li>
      <li>Demandes d’adhésion en ligne : identité, coordonnées, composition du foyer et pièces jointes que vous choisissez d’envoyer. Elles sont transmises uniquement à la mutuelle choisie ; les pièces sont conservées hors de l’espace public du site et ne sont lisibles que par vous et les agents habilités de cette mutuelle.</li>
    </ul>
    <h2 style="font-size:18px">Ce que nous ne collectons pas sur le réseau social</h2>
    <p>Aucune donnée médicale n'est demandée. Les dossiers d'adhérents, cotisations et prestations restent dans l'espace de gestion sécurisé de chaque mutuelle, séparé du réseau public, et ne sont jamais publiés.</p>
    <h2 style="font-size:18px">Vos choix</h2>
    <ul style="padding-left:18px">
      <li>Rendre votre profil privé, modifier ou retirer votre photo (Paramètres).</li>
      <li>Supprimer vos publications et commentaires à tout moment.</li>
      <li>Ne plus suivre ou masquer une mutuelle.</li>
      <li>Supprimer vous-même votre compte et vos données du réseau social (Paramètres → Supprimer mon compte).</li>
    </ul>
    <h2 style="font-size:18px">Photos</h2>
    <p>Les images publiées sont réencodées par le serveur : les métadonnées (position GPS, appareil…) sont supprimées.</p>
